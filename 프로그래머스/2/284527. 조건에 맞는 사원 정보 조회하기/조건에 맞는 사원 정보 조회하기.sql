SELECT SUM(B.SCORE) AS SCORE, A.EMP_NO, A.EMP_NAME, A.POSITION, A.EMAIL 
FROM HR_EMPLOYEES AS A JOIN HR_GRADE AS B ON A.EMP_NO = B.EMP_NO
WHERE B.YEAR = 2022
GROUP BY A.EMP_NO, B.YEAR
HAVING SUM(B.SCORE) = (
    SELECT MAX(TOTAL_SCORE)
    FROM (
        SELECT SUM(SCORE) AS TOTAL_SCORE
        FROM HR_GRADE
        WHERE YEAR = 2022
        GROUP BY EMP_NO
    ) AS T
)
ORDER BY SCORE DESC